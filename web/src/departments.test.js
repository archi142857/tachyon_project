import { describe, expect, it } from 'vitest';
import DEPARTMENTS from './departments.json';
import { matchDepartments } from './setup.js';

// 11-13 사람: '농생대는 세부 전공으로 검색했을 때 안 찾아짐 — 나머지 학부도 그런 거 있나'(기록 Tachyon-컨셉-23).
// 세부 전공 이름으로 찾으면 '학부 전공'이 맨 앞 몇 개 안에 나와야 한다.
const CASES = [
  ['동물생명공학전공', '식품·동물생명공학부 동물생명공학전공'],
  ['식품생명공학', '식품·동물생명공학부 식품생명공학전공'],
  ['응용생물학', '응용생물화학부 응용생물학전공'],
  ['응용생명화학', '응용생물화학부 응용생명화학전공'],
  ['조경학', '조경·지역시스템공학부 조경학전공'],
  ['원예', '식물생산과학부 원예생명공학전공'],
  ['작물', '식물생산과학부 작물생명과학전공'],
  ['산림환경', '산림과학부 산림환경학전공'],
  ['환경재료', '산림과학부 환경재료과학전공'],
  ['바이오소재', '바이오시스템·소재학부 바이오소재공학전공'],
  ['지역정보', '농경제사회학부 지역정보학전공'],
  ['농업자원경제', '농경제사회학부 농업·자원경제학전공'],
  ['스마트시스템', '스마트시스템과학과'],
  ['시각디자인', '디자인과 시각디자인전공'],
  ['도자공예', '공예과 도자공예전공'],
  ['관악전공', '관현악과 관악전공'],
  ['국악과 이론', '국악과 이론전공'],
  ['융합학습과학', '융합학습과학전공'],
];

describe('첫 설정 학과 찾기 — 세부 전공', () => {
  it.each(CASES)("'%s'로 찾으면 '%s'가 나온다", (query, name) => {
    const top = matchDepartments(DEPARTMENTS.list, query)
      .slice(0, 5)
      .map(([n]) => n);
    expect(top).toContain(name);
  });

  it('이름이 겹치지 않는다', () => {
    const names = DEPARTMENTS.list.map(([n]) => n);
    expect(new Set(names).size).toBe(names.length);
  });
});
